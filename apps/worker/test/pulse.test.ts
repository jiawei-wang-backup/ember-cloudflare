it("queries the configured LAN Dashboard for the bound workspace and never falls back to the old API",async()=>{
  const ada=await signIn("Ada"),room=await createRoom("Game",{as:ada,closedTo:[ada.user.id]});
  const bindings:Partial<Env>={PULSE_SOURCE:"dashboard",PULSE_URL:"http://192.168.16.70:4185",PULSE_HTTP_ORIGIN:"http://192.168.16.70:4185",PULSE_ROOMS:JSON.stringify({[room.id]:{projectId:"juxon-ai/deltaforce-game-library",memberIds:[ada.user.id]}})};
  const dashboard={projects:[],project_reports:[{project_key:"juxon-ai/deltaforce-game-library",goal:"游戏资料库",observed_at:"2026-11-16",milestones:[]}],workspace_states:[],project_usage:[],memberships:[],sessions:[],pulls:[],quota:[{secret:"global quota must not escape"}],models:[{model:"global model must not escape"}]};
  const fetch=vi.spyOn(globalThis,"fetch").mockImplementation(async()=>Response.json(dashboard));
  const response=await apiWith(bindings,`/api/rooms/${room.id}/project?days=1&projectId=other`,{headers:{Cookie:ada.cookie}});
  expect(response.status).toBe(200);
  const data=await response.json() as {project:{key:string;repository_id:null};source:string};
  expect(data.project).toMatchObject({key:"juxon-ai/deltaforce-game-library",repository_id:null});
  expect(data.source).toBe("http://192.168.16.70:4185/api/v1/dashboard?days=1");
  expect(JSON.stringify(data)).not.toContain("must not escape");
  expect(String(fetch.mock.calls[0]![0])).toBe(data.source);
  expect(fetch.mock.calls[0]![1]?.redirect).toBe("manual");
  const tools=projectTools({...runtimeEnv,...bindings} as Env,room.id,ada.user.id);
  const tool=tools.find(tool=>tool.name==="get_project_overview")!;
  const scoped=JSON.parse((await tool.run({days:1})).text);
  expect(scoped.project_id).toBe("juxon-ai/deltaforce-game-library");
  expect(scoped.project.key).toBe(scoped.project_id);
  expect(scoped.source).toBe(data.source);
  expect(scoped.quota).toBeUndefined();
  fetch.mockClear().mockResolvedValue(new Response(null,{status:503}));
  expect((await apiWith(bindings,`/api/rooms/${room.id}/project`,{headers:{Cookie:ada.cookie}})).status).toBe(502);
  expect(fetch).toHaveBeenCalledTimes(1);
  expect(String(fetch.mock.calls[0]![0])).not.toContain("4186");
});

it("shows only the authorized verified snapshot while a shared live request is still pending", async () => {
  const ada = await signIn("Ada"), room = await createRoom("Pulse demo", {as: ada, closedTo: [ada.user.id]});
  const key = "juxon-ai/project-pulse", source = "https://demo-background.example/api/v1/dashboard?days=7";
  const dashboard = {projects: [], project_reports: [{project_key: key, goal: "核对项目产出", observed_at: "2026-11-16", milestones: []}], workspace_states: [], project_usage: [], memberships: [], sessions: [], pulls: []};
  const saved = {...dashboardProject(dashboard, key, 7, source, new Date("2026-11-16T00:00:00Z")), freshness: {status: "snapshot", captured_at: "2026-11-16T00:00:00Z"}};
  const bindings = {...runtimeEnv, PULSE_SOURCE: "dashboard", PULSE_URL: "https://demo-background.example", PULSE_DEMO_SNAPSHOTS: JSON.stringify({[key]: saved}), PULSE_ROOMS: JSON.stringify({[room.id]: {projectId: key, memberIds: [ada.user.id]}})} as Env;
  let finish!: (response: Response) => void;
  vi.spyOn(globalThis, "fetch").mockImplementation(() => new Promise(resolve => {finish = resolve;}));
  const work: Promise<unknown>[] = [];
  const request = new Request(`https://ember.test/api/rooms/${room.id}/project`, {headers: {Cookie: ada.cookie}});
  const response = await pulseRoute(request, bindings, room.id, promise => work.push(promise));
  expect(response.status).toBe(200);
  expect(await response.json()).toMatchObject({project: {key}, freshness: {status: "snapshot", captured_at: saved.freshness.captured_at}});
  finish(Response.json(dashboard)); await Promise.all(work);
  const live = await pulseRoute(request, bindings, room.id, promise => work.push(promise));
  expect(await live.json()).toMatchObject({project: {key}, freshness: {status: "live"}});
});
